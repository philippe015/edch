export type ActionLanguage = "auto" | "fr" | "en";
const STORAGE = "edch.controls.actionLanguage";
const VALID: ActionLanguage[] = ["auto", "fr", "en"];

export function actionLanguageChoice(): ActionLanguage {
  try {
    const applied = "edch.controls.frKeysApplied.v1.3.1";
    if (lang().code === "fr" && localStorage.getItem(applied) !== "1") {
      localStorage.setItem(applied, "1");
      localStorage.setItem(STORAGE, "fr");
    }
    const saved = localStorage.getItem(STORAGE) as ActionLanguage | null;
    return saved && VALID.includes(saved) ? saved : lang().code === "fr" ? "fr" : "auto";
  } catch {
    return lang().code === "fr" ? "fr" : "auto";
  }
}

export function setActionLanguageChoice(value: ActionLanguage): void {
  if (!VALID.includes(value)) return;
  try {
    localStorage.setItem(STORAGE, value);
  } catch {
    /* UI still works */
  }
}

export function actionLanguage(): "fr" | "en" {
  const selected = actionLanguageChoice();
  return selected === "auto" ? (lang().code === "fr" ? "fr" : "en") : selected;
}

