/** The physical key's translated name; axes, joystick buttons and IDs are preserved. */
export function localizedKeyLabel(meta: BindsMeta, key: string): string {
  const source = keyLabel(meta, key);
  if (actionLanguage() !== "fr") return source;
  if (key in FR_KEY_CODES) return FR_KEY_CODES[key];
  if (key.startsWith("Key_")) return FR_KEY_ALIAS[source] ?? source;
  return source;
}

/** A complete binding including modifiers: e.g. "Maj gauche + A". */
export function localizedComboLabel(meta: BindsMeta, bind: Bind): string {
  const labels = [...bind.modifiers.map((m) => localizedKeyLabel(meta, m.key)), localizedKeyLabel(meta, bind.key)];
  return labels.join(" + ");
}

