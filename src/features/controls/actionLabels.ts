/** Display label with source action ID available separately for technical diagnosis. */
export function localizedActionLabel(meta: BindsMeta, action: string): string {
  const original = englishActionLabel(meta, action);
  return actionLanguage() === "fr" ? frenchActionWithFallback(original) : original;
}

